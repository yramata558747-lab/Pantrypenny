import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:hive_flutter/hive_flutter.dart';
import 'package:provider/provider.dart';

import 'firebase_options.dart';
import 'models/auth_provider.dart';
import 'models/pantry_item.dart';
import 'models/pantry_provider.dart';
import 'models/restock_item.dart';
import 'models/restock_provider.dart';
import 'screens/auth_screen.dart';
import 'screens/pantry_screen.dart';
import 'theme/pantry_style.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Firebase (generated by `flutterfire configure`).
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  // Hive (existing local data is kept).
  await Hive.initFlutter();

  if (!Hive.isAdapterRegistered(0)) {
    Hive.registerAdapter(PantryItemAdapter());
  }

  if (!Hive.isAdapterRegistered(1)) {
    Hive.registerAdapter(RestockItemAdapter());
  }

  final auth = AuthProvider();
  final pantry = PantryProvider();
  final restock = RestockProvider();

  await auth.init();
  await pantry.init();
  await restock.init();

  runApp(
    MultiProvider(
      providers: [
        ChangeNotifierProvider<AuthProvider>.value(value: auth),
        ChangeNotifierProvider<PantryProvider>.value(value: pantry),
        ChangeNotifierProvider<RestockProvider>.value(value: restock),
      ],
      child: const PantryPennyApp(),
    ),
  );
}

class PantryPennyApp extends StatelessWidget {
  const PantryPennyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      title: 'PantryPenny',
      theme: PantryStyle.theme(),
      home: const AuthGate(),
    );
  }
}

/// Shows the pantry only for a signed-in, email-verified user.
class AuthGate extends StatelessWidget {
  const AuthGate({super.key});

  @override
  Widget build(BuildContext context) {
    final auth = context.watch<AuthProvider>();

    if (!auth.isReady) {
      return const Scaffold(
        body: Center(child: CircularProgressIndicator()),
      );
    }

    if (auth.isLoggedIn) {
      return const _SignedInHome();
    }

    return const AuthScreen();
  }
}

class _SignedInHome extends StatefulWidget {
  const _SignedInHome();

  @override
  State<_SignedInHome> createState() => _SignedInHomeState();
}

class _SignedInHomeState extends State<_SignedInHome> {
  @override
  void initState() {
    super.initState();

    // Upload existing local pantry data once after login.
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) {
        context.read<PantryProvider>().syncAllToCloud();
      }
    });
  }

  @override
  Widget build(BuildContext context) => const PantryScreen();
}